/** 全文をプレーンテキストで組み立てる（コピー用・テスト用）。 */
export function disclaimerPlainText(): string {
  const body = disclaimerSections().map(
    (section, i) => `${i + 1}. ${section.title}\n${section.body}`,
  ).join("\n\n");
  return `【${DISCLAIMER_TITLE}】\n\n${body}`;
}
